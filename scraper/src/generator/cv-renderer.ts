/**
 * Generates ATS Single-Column Strict HTML string from candidate data and selected bullets.
 */
export function generateCvHtml(
  cvData: CandidateCvData,
  selectedBullets: CandidateBullet[],
  options?: Partial<RenderCvOptions & { compact?: boolean }>
): string {
  const language = options?.language || 'pl';
  const compact = options?.compact ?? false;

  const contactsHtml = formatContactLinks(cvData.contacts);
  const skillsHtml = formatSkillsMatrixHtml(cvData.skills);
  const experienceHtml = formatExperienceHtml(selectedBullets);
  const cleanSummary = sanitizeEmployerSummary(cvData.summary);
  const css = getCvCss({ compact });

  // Use Polish RODO clause by default or English based on language selection
  const rodoText =
    language === 'en'
      ? cvData.rodoClause?.en || DEFAULT_RODO_CLAUSE.en
      : cvData.rodoClause?.pl || DEFAULT_RODO_CLAUSE.pl;

  return `<!DOCTYPE html>
<html lang="${language}">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${escapeHtml(cvData.contacts.name)} — CV</title>
  <style>
${css}
  </style>
</head>
<body class="ats-cv">
  <div class="cv-container">
    <header class="cv-header">
      <h1 class="candidate-name">${escapeHtml(cvData.contacts.name)}</h1>
      <p class="candidate-contacts">${contactsHtml}</p>
    </header>

    ${
      cleanSummary
        ? `    <section class="cv-section cv-summary">
      <h2 class="section-title">Professional Summary</h2>
      <p class="summary-text">${escapeHtml(cleanSummary)}</p>
    </section>`
        : ''
    }

    ${skillsHtml}

${experienceHtml}

    <section class="cv-section cv-education">
      <h2 class="section-title">Education &amp; Languages</h2>
      <p class="summary-text"><strong>Bachelor&#39;s Degree in Management of Information Resources</strong> — Yanka Kupala State University of Grodno, Faculty of Mathematics and Computer Science (2012 – 2016)</p>
      <p class="summary-text" style="margin-top: 2px;"><strong>Languages:</strong> English (Professional / C1), Polish (Intermediate / B1), Russian (Native)</p>
    </section>

    <footer class="rodo-clause">
      <p class="rodo-text">${escapeHtml(rodoText)}</p>
    </footer>
  </div>
</body>
</html>`;
}

// ── 4. Browser Resolution & Lifecycle Helper ────────────────────────────────

export interface BrowserSession {
  browser: Browser;
  context: BrowserContext;
  page: Page;
  isShared: boolean;
}

/**
 * Acquires a Chromium page and context, reusing an injected browser, the shared
 * browser from utils/browser, or launching a dedicated headless Chromium instance.
 */
export async function acquireBrowserSession(
  injectedBrowser?: Browser
): Promise<BrowserSession> {
  let browser: Browser;
  let isShared = false;

  if (injectedBrowser) {
    browser = injectedBrowser;
    isShared = true;
  } else {
    browser = await chromium.launch({
      headless: true,
      args: [
        '--no-sandbox',
        '--disable-setuid-sandbox',
        '--disable-dev-shm-usage',
        '--disable-gpu',
      ],
    });
    isShared = false;
  }

  const context = await browser.newContext();
  const page = await context.newPage();

  return { browser, context, page, isShared };
}

// ── 5. Core Renderer: renderCvToPdf ─────────────────────────────────────────

/**
 * Renders an ATS-compliant CV into a vector PDF file using Playwright headless Chromium.
 *
 * Guarantees:
 * - Single-Column Strict layout (no tables, no icons, no progress bars).
 * - Vector text selection and clickable hyperlinks (mailto:, https:, tel:).
 * - Strictly 1 or 2 A4 pages without empty overflow pages.
 * - Under each role: "Environment / Tech Stack:" line.
 * - Polish RODO clause at the end.
 *
 * @param cvData - Master CV candidate profile data from Notion loader.
 * @param selectedBullets - Bullets selected by Pre-Ranker / Assembler.
 * @param options - Output path, language, and optional page limit (1 or 2).
 * @param injectedBrowser - Optional injected Playwright Browser instance.
 * @returns Object with pdfPath, pageCount, and bufferSize.
 */
export async function renderCvToPdf(
  cvData: CandidateCvData,
  selectedBullets: CandidateBullet[],
  options: RenderCvOptions,
  injectedBrowser?: Browser
): Promise<RenderCvResult> {
  if (!options || !options.outputPath) {
    throw new Error('RenderCvOptions.outputPath is required');
  }
  if (!cvData || !cvData.contacts) {
    throw new Error('CandidateCvData with valid contacts is required');
  }

  const targetLimit = options.pageLimit ?? 2;
  const targetDir = path.dirname(options.outputPath);
  if (!fs.existsSync(targetDir)) {
    fs.mkdirSync(targetDir, { recursive: true });
  }

  const session = await acquireBrowserSession(injectedBrowser);

  try {
    // 1. First render pass: Standard layout
    let html = generateCvHtml(cvData, selectedBullets, {
      ...options,
      compact: false,
    });
    await session.page.setContent(html, { waitUntil: 'load' });

    let pdfBuffer = await session.page.pdf({
      format: 'A4',
      printBackground: true,
      preferCSSPageSize: true,
      displayHeaderFooter: false,
    });

    let pageCount = extractPdfPageCount(pdfBuffer);

    // 2. Second pass: If pageCount exceeds target budget, attempt compact mode
    if (pageCount > targetLimit) {
      html = generateCvHtml(cvData, selectedBullets, {
        ...options,
        compact: true,
      });
      await session.page.setContent(html, { waitUntil: 'load' });

      pdfBuffer = await session.page.pdf({
        format: 'A4',
        printBackground: true,
        preferCSSPageSize: true,
        scale: 0.95,
        displayHeaderFooter: false,
      });

      pageCount = extractPdfPageCount(pdfBuffer);
    }

    // 3. Third pass: If still exceeds and target is 1 page, attempt tighter scale
    if (pageCount > targetLimit && targetLimit === 1) {
      pdfBuffer = await session.page.pdf({
        format: 'A4',
        printBackground: true,
        preferCSSPageSize: true,
        scale: 0.72,
        displayHeaderFooter: false,
      });

      pageCount = extractPdfPageCount(pdfBuffer);
    }

    // 4. Page Budget Enforcement: strictly 1 or 2 pages without overflow
    if (pageCount > targetLimit) {
      throw new Error(
        `Rendered CV exceeds page budget: generated ${pageCount} pages, maximum allowed is ${targetLimit}.`
      );
    }

    // 5. Save PDF to destination
    fs.writeFileSync(options.outputPath, pdfBuffer);

    return {
      pdfPath: options.outputPath,
      pageCount,
      bufferSize: pdfBuffer.length,
    };
  } finally {
    // Clean up Playwright resources without leaking processes
    await session.page.close().catch(() => {});
    await session.context.close().catch(() => {});
    if (!session.isShared) {
      await session.browser.close().catch(() => {});
    }
  }
}

/**
 * Fast Base Gold CV PDF Retriever (Slice 3).
 * Returns the path and buffer of the gold standard ATS CV in < 0.05 seconds
 * when cached, eliminating Playwright Chromium startup latency during live Telegram bot replies.
 */
export async function getBaseCvPdf(
  cvData?: CandidateCvData,
  options?: {
    destinationDir?: string;
    forceRender?: boolean;
    cachedPdfPath?: string;
  }
): Promise<{ pdfPath: string; buffer: Buffer; fromCache: boolean }> {
  const baseDir = options?.destinationDir || path.resolve(process.cwd(), 'output');
  const targetPdf = options?.cachedPdfPath || path.join(baseDir, 'gold_base_cv.pdf');

  if (!options?.forceRender && fs.existsSync(targetPdf)) {
    const stats = fs.statSync(targetPdf);
    if (stats.size > 0) {
      const buffer = fs.readFileSync(targetPdf);
      return { pdfPath: targetPdf, buffer, fromCache: true };
    }
  }

  const { DEFAULT_CANDIDATE_CV_DATA } = await import('./notion-loader');
  const data = cvData || DEFAULT_CANDIDATE_CV_DATA;
  if (!fs.existsSync(baseDir)) {
    fs.mkdirSync(baseDir, { recursive: true });
  }

  try {
    const res = await renderCvToPdf(data, data.bullets, {
      outputPath: targetPdf,
      pageLimit: 2,
    });
    const buffer = fs.readFileSync(res.pdfPath);
    return { pdfPath: targetPdf, buffer, fromCache: false };
  } catch (err) {
    if (fs.existsSync(targetPdf)) {
      const buffer = fs.readFileSync(targetPdf);
      return { pdfPath: targetPdf, buffer, fromCache: true };
    }
    throw err;
  }
}
