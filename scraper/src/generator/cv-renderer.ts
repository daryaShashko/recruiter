// ── 1. HTML Escaping Utility ────────────────────────────────────────────────

export function escapeHtml(str: string): string {
  if (!str) return '';
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

// ── 2. PDF Page Count Extractor (Dependency-Free) ───────────────────────────

/**
 * Extracts the exact page count from a generated PDF buffer.
 * Examines PDF structure using multiple redundant checks:
 * 1. Dictionaries containing `/Type /Pages` with `/Count <N>`
 * 2. Flat regex for `/Type /Pages ... /Count <N>`
 * 3. Counting individual `/Type /Page` leaf objects (excluding `/Pages` via word boundary)
 *
 * @param pdfBuffer - Raw PDF buffer generated by Chromium page.pdf().
 * @returns Number of pages (positive integer, at least 1).
 */
export function extractPdfPageCount(pdfBuffer: Buffer): number {
  if (!pdfBuffer || pdfBuffer.length === 0) {
    return 1;
  }

  const binaryString = pdfBuffer.toString('binary');

  // Method 1: Find dictionaries containing /Type /Pages and extract /Count N
  const dictMatches = binaryString.match(/<<[\s\S]*?>>/g) || [];
  for (const dict of dictMatches) {
    if (/\/Type\s*\/Pages\b/.test(dict)) {
      const countMatch = dict.match(/\/Count\s+(\d+)\b/);
      if (countMatch && countMatch[1]) {
        const count = parseInt(countMatch[1], 10);
        if (!isNaN(count) && count > 0) {
          return count;
        }
      }
    }
  }

  // Method 2: Match /Type /Pages ... /Count N without dictionary boundaries
  const pagesMatch = binaryString.match(/\/Type\s*\/Pages[\s\S]*?\/Count\s+(\d+)\b/);
  if (pagesMatch && pagesMatch[1]) {
    const count = parseInt(pagesMatch[1], 10);
    if (!isNaN(count) && count > 0) {
      return count;
    }
  }

  const countFirstMatch = binaryString.match(/\/Count\s+(\d+)\b[\s\S]*?\/Type\s*\/Pages\b/);
  if (countFirstMatch && countFirstMatch[1]) {
    const count = parseInt(countFirstMatch[1], 10);
    if (!isNaN(count) && count > 0) {
      return count;
    }
  }

  // Method 3: Count individual /Type /Page objects (excluding /Pages)
  const pageMatches = binaryString.match(/\/Type\s*\/Page\b/g);
  if (pageMatches && pageMatches.length > 0) {
    return pageMatches.length;
  }

  return 1;
}

// ── 3. HTML Layout & Styling Generators ──────────────────────────────────────

/**
 * Clean URL representation for display (strips protocol and trailing slash).
 */
function cleanUrlDisplay(url: string): string {
  return url.replace(/^https?:\/\/(www\.)?/, '').replace(/\/$/, '');
}

/**
 * Renders contact header links as clickable HTML with semantic separators.
 * Strictly excludes photos, age, marital status, and exact street address.
 */
export function formatContactLinks(contacts: CandidateContacts): string {
  if (!contacts) return '';
  const items: string[] = [];

  if (contacts.location) {
    items.push(`<span class="contact-item">${escapeHtml(contacts.location)}</span>`);
  }
  if (contacts.phone) {
    items.push(
      `<span class="contact-item"><a href="tel:${escapeHtml(
        contacts.phone.replace(/\s+/g, '')
      )}">${escapeHtml(contacts.phone)}</a></span>`
    );
  }
  if (contacts.email) {
    items.push(
      `<span class="contact-item"><a href="mailto:${escapeHtml(
        contacts.email
      )}">${escapeHtml(contacts.email)}</a></span>`
    );
  }
  if (contacts.linkedIn) {
    items.push(
      `<span class="contact-item"><a href="${escapeHtml(
        contacts.linkedIn
      )}" target="_blank" rel="noopener noreferrer">${escapeHtml(
        cleanUrlDisplay(contacts.linkedIn)
      )}</a></span>`
    );
  }
  if (contacts.github) {
    items.push(
      `<span class="contact-item"><a href="${escapeHtml(
        contacts.github
      )}" target="_blank" rel="noopener noreferrer">${escapeHtml(
        cleanUrlDisplay(contacts.github)
      )}</a></span>`
    );
  }

  return items.join('<span class="contact-separator">•</span>');
}

/**
 * Formats the 5-category skills matrix as clean text lists without tables or progress bars.
 */
export function formatSkillsMatrixHtml(skills: Record<string, string[]>): string {
  if (!skills) return '';
  const matrix = buildSkillsMatrix(skills);
  return renderSkillsMatrixHtml(matrix);
}

export interface BulletRoleGroup {
  title: string;
  period?: string;
  bullets: CandidateBullet[];
  tags: string[];
}

/**
 * Strips internal LLM-evaluator directives and Notion template placeholders
 * so employer-facing CV documents remain 100% professional.
 */
export function sanitizeEmployerSummary(summary?: string): string {
  if (!summary) return '';
  return summary
    .replace(/\s*Strictly\s+NO\s+Junior,\s*Mid-level,\s*or\s*Regular\s+positions\.?/gi, '')
    .trim();
}

export function sanitizeEmployerBullet(bullet: CandidateBullet): CandidateBullet {
  let title = bullet.title || '';
  let highlight = bullet.highlight || '';

  // Replace unedited Notion provisioning placeholder with clean project entry
  if (/Fill in your new experience here/i.test(title)) {
    title = 'AI Recruiter & Autonomous LLM Evaluation Platform';
  }
  if (/update this row in Notion with your new stack/i.test(highlight)) {
    highlight =
      'Architected and delivered an end-to-end AI job evaluation and ATS application pipeline using TypeScript, Node.js, Playwright, and Promptfoo.';
  }

  // Strip internal evaluator prompt notes from highlights
  highlight = highlight
    .replace(/\s*Strictly\s+NO\s+Junior,\s*Mid-level,\s*or\s*Regular\s+positions\.?/gi, '')
    .replace(
      /\s*\(job postings in Polish are acceptable,\s*but fluent spoken Polish must NOT be a hard requirement\)/gi,
      ''
    )
    .replace(
      /\s*\(NO 100% people management without coding,\s*and NO zero-impact pure coder role\)/gi,
      ''
    )
    .trim();

  return {
    ...bullet,
    title,
    highlight,
  };
}

/**
 * Groups candidate bullets by title/period into cohesive role items,
 * guaranteeing Google XYZ verbatim highlights and a dedicated "Environment / Tech Stack:" line.
 */
export function groupBulletsIntoRoles(bullets: CandidateBullet[]): BulletRoleGroup[] {
  if (!bullets || bullets.length === 0) return [];

  const groups: BulletRoleGroup[] = [];
  const map = new Map<string, BulletRoleGroup>();

  for (const rawBullet of bullets) {
    const bullet = sanitizeEmployerBullet(rawBullet);
    const roleTitle = bullet.title || bullet.section || 'Key Experience';
    const key = `${roleTitle}__${bullet.period || ''}`;
    let group = map.get(key);
    if (!group) {
      group = {
        title: roleTitle,
        period: bullet.period,
        bullets: [],
        tags: [],
      };
      map.set(key, group);
      groups.push(group);
    }
    group.bullets.push(bullet);
    for (const tag of Array.isArray(bullet.tags) ? bullet.tags : []) {
      if (typeof tag === 'string' && tag.trim().length > 0) {
        const cleanTag = tag.trim();
        if (!group.tags.includes(cleanTag)) {
          group.tags.push(cleanTag);
        }
      }
    }
  }

  return groups;
}

/**
 * Renders the Experience section with role blocks, Google XYZ bullets, and Environment line.
 */
export function formatExperienceHtml(bullets: CandidateBullet[]): string {
  if (!bullets || bullets.length === 0) return '';

  const roleGroups = groupBulletsIntoRoles(bullets);

  const itemsHtml = roleGroups
    .map((role) => {
      const bulletsList = role.bullets
        .map((b) => `        <li class="exp-bullet">${escapeHtml(b.highlight)}</li>`)
        .join('\n');

      const techStack =
        role.tags.length > 0 ? role.tags.join(', ') : 'TypeScript, Node.js';

      return `      <div class="experience-item">
        <div class="role-header">
          <span class="role-title">${escapeHtml(role.title)}</span>
          ${
            role.period
              ? `<span class="role-period">${escapeHtml(role.period)}</span>`
              : ''
          }
        </div>
        <ul class="role-bullets">
${bulletsList}
        </ul>
        <div class="tech-stack-line"><strong>Environment / Tech Stack:</strong> ${escapeHtml(
          techStack
        )}</div>
      </div>`;
    })
    .join('\n');

  return `    <section class="cv-section cv-experience">
      <h2 class="section-title">Experience &amp; Key Achievements</h2>
      <div class="experience-list">
${itemsHtml}
      </div>
    </section>`;
}

